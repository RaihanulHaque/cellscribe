"""Build the CellScribe extension: WriterAgent plus a token-entry menu item.

The package is identical for every PC: it embeds only the gateway URL. Each
employee pastes their device token once (Tools > CellScribe: Enter access
token); the extension validates it against the gateway and writes WriterAgent's
writeragent.json. The Mistral key is never involved.

WriterAgent's own files are not modified. We add our handler and two
configuration files under cellscribe/, register them in the manifest, and drop
WriterAgent's update feed so the Extension Manager cannot swap our package for
the upstream one.
"""

from __future__ import annotations

import functools
import io
import json
import re
import zipfile

SERVICE = "org.cellscribe.ConfigHandler"
PROTOCOL = "org.cellscribe.config:"

_MANIFEST_ENTRIES = """  <manifest:file-entry manifest:media-type="application/vnd.sun.star.uno-component;type=Python" manifest:full-path="cellscribe/handler.py"/>
  <manifest:file-entry manifest:media-type="application/vnd.sun.star.configuration-data" manifest:full-path="cellscribe/ProtocolHandler.xcu"/>
  <manifest:file-entry manifest:media-type="application/vnd.sun.star.configuration-data" manifest:full-path="cellscribe/Addons.xcu"/>
"""

_PROTOCOL_HANDLER = """<?xml version="1.0" encoding="UTF-8"?>
<oor:component-data xmlns:oor="http://openoffice.org/2001/registry"
                    xmlns:xs="http://www.w3.org/2001/XMLSchema"
                    oor:name="ProtocolHandler" oor:package="org.openoffice.Office">
  <node oor:name="HandlerSet">
    <node oor:name="%(svc)s" oor:op="replace">
      <prop oor:name="Protocols" oor:type="oor:string-list">
        <value>%(proto)s*</value>
      </prop>
    </node>
  </node>
</oor:component-data>
"""

_ADDONS = """<?xml version="1.0" encoding="UTF-8"?>
<oor:component-data xmlns:oor="http://openoffice.org/2001/registry"
                    xmlns:xs="http://www.w3.org/2001/XMLSchema"
                    oor:name="Addons" oor:package="org.openoffice.Office">
  <node oor:name="AddonUI">
    <node oor:name="OfficeMenuBarMerge">
      <node oor:name="org.cellscribe.config.Menu" oor:op="replace">
        <prop oor:name="MergePoint"><value>.uno:ToolsMenu\\.uno:ConfigureDialog</value></prop>
        <prop oor:name="MergeCommand"><value>AddAfter</value></prop>
        <prop oor:name="MergeFallback"><value>AddPath</value></prop>
        <prop oor:name="MergeContext"><value>com.sun.star.text.TextDocument,com.sun.star.sheet.SpreadsheetDocument,com.sun.star.presentation.PresentationDocument,com.sun.star.drawing.DrawingDocument</value></prop>
        <node oor:name="MenuItems">
          <node oor:name="M1" oor:op="replace">
            <prop oor:name="URL"><value>%(proto)sSetToken</value></prop>
            <prop oor:name="Title"><value xml:lang="en-US">CellScribe: Enter access token...</value></prop>
            <prop oor:name="Target"><value>_self</value></prop>
          </node>
        </node>
      </node>
    </node>
  </node>
</oor:component-data>
"""

_HANDLER = '''# CellScribe configuration handler (generated by the gateway)
import json
import os
import urllib.error
import urllib.request

import uno
import unohelper
from com.sun.star.frame import XDispatch, XDispatchProvider
from com.sun.star.lang import XInitialization, XServiceInfo

SETTINGS = json.loads(%(settings)s)
SERVICE = "%(svc)s"
PROTOCOL = "%(proto)s"


def _config_path(ctx):
    subst = ctx.ServiceManager.createInstanceWithContext("com.sun.star.util.PathSubstitution", ctx)
    user = uno.fileUrlToSystemPath(subst.substituteVariables("$(user)", True))
    return os.path.join(user, "config", "writeragent.json")


def _load(path):
    if not os.path.exists(path):
        return {}
    with open(path, "r", encoding="utf-8") as handle:
        text = "\\n".join(l for l in handle.read().splitlines() if not l.lstrip().startswith("//"))
    try:
        data = json.loads(text)
    except ValueError:
        return {}
    return data if isinstance(data, dict) else {}


def check_token(token):
    """Ask the gateway which models this token may use. Returns (models, error)."""
    req = urllib.request.Request(
        SETTINGS["endpoint"] + "/v1/models", headers={"Authorization": "Bearer " + token}
    )
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        return [m["id"] for m in data.get("data", [])], None
    except urllib.error.HTTPError as exc:
        if exc.code == 401:
            return None, "The gateway rejected this token (wrong, or revoked)."
        return None, "Gateway error: HTTP %%d" %% exc.code
    except Exception as exc:
        return None, "Cannot reach the gateway at %%s (%%s)." %% (SETTINGS["endpoint"], exc)


def apply_token(ctx, token, model):
    path = _config_path(ctx)
    config = _load(path)
    endpoint = SETTINGS["endpoint"]
    keys = config.get("api_keys_by_endpoint")
    if not isinstance(keys, dict):
        keys = {}
    keys[endpoint] = token
    config["endpoint"] = endpoint
    config["api_keys_by_endpoint"] = keys
    config["text_model"] = model
    config["model"] = model
    config.setdefault("request_timeout", 300)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        json.dump(config, handle, indent=4)
    try:
        os.chmod(tmp, 0o600)
    except OSError:
        pass
    os.replace(tmp, path)
    return path


def _message(ctx, text, error=False):
    smgr = ctx.ServiceManager
    toolkit = smgr.createInstanceWithContext("com.sun.star.awt.Toolkit", ctx)
    desktop = smgr.createInstanceWithContext("com.sun.star.frame.Desktop", ctx)
    frame = desktop.getCurrentFrame()
    parent = frame.getContainerWindow() if frame else toolkit.getDesktopWindow()
    kind = uno.Enum("com.sun.star.awt.MessageBoxType", "ERRORBOX" if error else "INFOBOX")
    box = toolkit.createMessageBox(parent, kind, 1, "CellScribe", text)
    box.execute()


def _ask_token(ctx):
    """Show a small input dialog. Returns the pasted token or None."""
    smgr = ctx.ServiceManager
    model = smgr.createInstanceWithContext("com.sun.star.awt.UnoControlDialogModel", ctx)
    model.PositionX, model.PositionY, model.Width, model.Height = 0, 0, 230, 78
    model.Title = "CellScribe access token"

    def add(kind, name, **props):
        item = model.createInstance("com.sun.star.awt.UnoControl%%sModel" %% kind)
        item.Name = name
        for key, value in props.items():
            setattr(item, key, value)
        model.insertByName(name, item)

    add("FixedText", "lbl", PositionX=10, PositionY=8, Width=210, Height=20, MultiLine=True,
        Label="Paste the access token your administrator gave you:")
    add("Edit", "tok", PositionX=10, PositionY=30, Width=210, Height=14, Text="")
    add("Button", "ok", PositionX=60, PositionY=56, Width=50, Height=14, Label="Connect",
        PushButtonType=1, DefaultButton=True)
    add("Button", "cancel", PositionX=120, PositionY=56, Width=50, Height=14, Label="Cancel",
        PushButtonType=2)

    dialog = smgr.createInstanceWithContext("com.sun.star.awt.UnoControlDialog", ctx)
    dialog.setModel(model)
    toolkit = smgr.createInstanceWithContext("com.sun.star.awt.Toolkit", ctx)
    dialog.setVisible(False)
    dialog.createPeer(toolkit, None)
    result = dialog.execute()
    token = dialog.getControl("tok").getText().strip() if result == 1 else None
    dialog.dispose()
    return token


def run(ctx, token=None):
    interactive = token is None
    if interactive:
        token = _ask_token(ctx)
        if not token:
            return
    models, error = check_token(token)
    if error:
        if interactive:
            _message(ctx, error, error=True)
        return
    default = SETTINGS["model"]
    model = default if default in models else (models[0] if models else default)
    path = apply_token(ctx, token, model)
    if interactive:
        _message(ctx, "Connected. Using model %%s.\\nSettings saved; they apply within a few seconds "
                      "(restart LibreOffice if the AI features do not respond)." %% model)


class Dispatch(unohelper.Base, XDispatch):
    def __init__(self, ctx):
        self.ctx = ctx

    def dispatch(self, url, args):
        token = None
        for prop in args or ():
            if prop.Name == "Token":
                token = prop.Value
        try:
            run(self.ctx, token)
        except Exception as exc:
            try:
                _message(self.ctx, "CellScribe setup failed: %%s" %% exc, error=True)
            except Exception:
                pass

    def addStatusListener(self, listener, url):
        pass

    def removeStatusListener(self, listener, url):
        pass


class Handler(unohelper.Base, XDispatchProvider, XInitialization, XServiceInfo):
    def __init__(self, ctx):
        self.ctx = ctx

    def initialize(self, args):
        pass

    def queryDispatch(self, url, target, flags):
        if url.Complete.startswith(PROTOCOL):
            return Dispatch(self.ctx)
        return None

    def queryDispatches(self, requests):
        return tuple(self.queryDispatch(r.FeatureURL, r.FrameName, r.SearchFlags) for r in requests)

    def getImplementationName(self):
        return SERVICE

    def supportsService(self, name):
        return name == "com.sun.star.frame.ProtocolHandler"

    def getSupportedServiceNames(self):
        return ("com.sun.star.frame.ProtocolHandler",)


g_ImplementationHelper = unohelper.ImplementationHelper()
g_ImplementationHelper.addImplementation(Handler, SERVICE, ("com.sun.star.frame.ProtocolHandler",))
'''


@functools.lru_cache(maxsize=8)
def build_oxt(base_oxt: str, endpoint: str, default_model: str) -> bytes:
    """Return the bytes of WriterAgent with the CellScribe additions."""
    settings = json.dumps({"endpoint": endpoint, "model": default_model})
    fmt = {"settings": repr(settings), "svc": SERVICE, "proto": PROTOCOL}
    buf = io.BytesIO()
    with zipfile.ZipFile(base_oxt) as src, zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as out:
        for item in src.infolist():
            data = src.read(item.filename)
            if item.filename == "META-INF/manifest.xml":
                text = data.decode("utf-8")
                if "</manifest:manifest>" not in text:
                    raise ValueError("Unexpected manifest.xml in base extension")
                data = text.replace("</manifest:manifest>", _MANIFEST_ENTRIES + "</manifest:manifest>").encode("utf-8")
            elif item.filename == "description.xml":
                text = data.decode("utf-8")
                text = re.sub(r"\s*<update-information>.*?</update-information>", "", text, flags=re.S)
                data = text.encode("utf-8")
            out.writestr(item, data)
        out.writestr("cellscribe/ProtocolHandler.xcu", _PROTOCOL_HANDLER % fmt)
        out.writestr("cellscribe/Addons.xcu", _ADDONS % fmt)
        out.writestr("cellscribe/handler.py", _HANDLER % fmt)
    return buf.getvalue()
